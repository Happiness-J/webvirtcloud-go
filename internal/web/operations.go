func (s *Server) storageAction(w http.ResponseWriter, r *http.Request) {
	host, err := s.db.GetHost(r.Context(), r.PathValue("id"))
	if err != nil {
		s.hostLookupError(w, r, err)
		return
	}
	sess, _ := sessionFrom(r.Context())
	pool := strings.TrimSpace(r.Form.Get("pool"))
	volume := strings.TrimSpace(r.Form.Get("volume"))
	name := strings.TrimSpace(r.Form.Get("name"))
	capacity := strings.ToUpper(strings.TrimSpace(r.Form.Get("capacity")))
	action := strings.TrimSpace(r.Form.Get("action"))
	if err := libvirt.ValidateName(pool); err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/storage?pool="+url.QueryEscape(pool), "存储池名称无效")
		return
	}

	var args []string
	label := ""
	switch action {
	case "pool-info":
		s.renderStorageDiagnostic(w, r, host, pool)
		return
	case "pool-capacity":
		s.renderStorageDiagnostic(w, r, host, pool)
		return
	case "pool-refresh":
		args = []string{"pool-refresh", pool}
		label = "刷新存储池 " + pool
	case "pool-start":
		args = []string{"pool-start", pool}
		label = "启动存储池 " + pool
	case "pool-autostart-on":
		args = []string{"pool-autostart", pool}
		label = "设置存储池自启动 " + pool
	case "pool-autostart-off":
		args = []string{"pool-autostart", "--disable", pool}
		label = "取消存储池自启动 " + pool
	case "volume-create":
		if err := libvirt.ValidateName(name); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "卷名称无效")
			return
		}
		if _, err := parseScaledAmount(capacity); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "卷容量格式无效，例如 10G")
			return
		}
		format := strings.ToLower(strings.TrimSpace(r.Form.Get("format")))
		if !validVolumeFormat(format) {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "卷格式无效")
			return
		}
		args = []string{"vol-create-as", pool, name, capacity, "--format", format}
		label = fmt.Sprintf("创建卷 %s/%s", pool, name)
	case "volume-clone":
		if err := libvirt.ValidateName(volume); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "源卷名称无效")
			return
		}
		if err := libvirt.ValidateName(name); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "新卷名称无效")
			return
		}
		args = []string{"vol-clone", "--pool", pool, volume, name}
		label = fmt.Sprintf("克隆卷 %s/%s -> %s", pool, volume, name)
	case "volume-resize":
		if err := libvirt.ValidateName(volume); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "卷名称无效")
			return
		}
		if _, err := parseScaledAmount(capacity); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "调整容量格式无效，例如 10G")
			return
		}
		mode := strings.ToLower(strings.TrimSpace(r.Form.Get("resize_mode")))
		switch mode {
		case "grow":
			args = []string{"vol-resize", "--pool", pool, "--delta", volume, capacity}
			label = fmt.Sprintf("扩容卷 %s/%s +%s", pool, volume, capacity)
		case "shrink":
			if r.Form.Get("confirm_text") != "SHRINK" {
				s.redirectError(w, r, storageRedirect(host.ID, pool), "卷缩容必须输入 SHRINK")
				return
			}
			args = []string{"vol-resize", "--pool", pool, "--delta", "--shrink", volume, capacity}
			label = fmt.Sprintf("缩容卷 %s/%s -%s", pool, volume, capacity)
		default:
			s.redirectError(w, r, storageRedirect(host.ID, pool), "请选择扩容或缩容")
			return
		}
	case "volume-filesystems":
		if err := libvirt.ValidateName(volume); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "卷名称无效")
			return
		}
		volumes, volErr := s.libvirt.ListVolumes(r.Context(), host.ID, pool)
		if volErr != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "无法读取存储卷")
			return
		}
		path := ""
		for _, item := range volumes {
			if item.Name == volume {
				path = item.Path
				break
			}
		}
		if path == "" || !strings.HasPrefix(path, "/") || strings.Contains(path, "..") {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "该卷没有可检查的本地磁盘路径")
			return
		}
		jobID, err := s.enqueueCommand(r, sess.User, host.ID, "filesystem-inspect", "检查文件系统 "+volume, "virt-filesystems", []string{"-a", path, "--all", "--long", "--human-readable"}, "", boundedOperationTimeout(s.cfg.MaxTimeout, 300))
		if err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), err.Error())
			return
		}
		// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
		http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
		return
	case "volume-delete":
		if err := libvirt.ValidateName(volume); err != nil {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "卷名称无效")
			return
		}
		if r.Form.Get("confirm") != "yes" {
			s.redirectError(w, r, storageRedirect(host.ID, pool), "删除卷需要显式确认")
			return
		}
		args = []string{"vol-delete", "--pool", pool, volume}
		label = fmt.Sprintf("删除卷 %s/%s", pool, volume)
	default:
		s.redirectError(w, r, storageRedirect(host.ID, pool), "未知存储操作")
		return
	}
	jobID, err := s.enqueueCommand(r, sess.User, host.ID, "storage-action", label, "virsh", args, "", boundedOperationTimeout(s.cfg.MaxTimeout, 300))
	if err != nil {
		s.redirectError(w, r, storageRedirect(host.ID, pool), err.Error())
		return
	}
	// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
	http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
}

func (s *Server) networkAction(w http.ResponseWriter, r *http.Request) {
	host, err := s.db.GetHost(r.Context(), r.PathValue("id"))
	if err != nil {
		s.hostLookupError(w, r, err)
		return
	}
	networkName := strings.TrimSpace(r.Form.Get("network"))
	if err := libvirt.ValidateName(networkName); err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/networks", "虚拟网络名称无效")
		return
	}
	action := strings.TrimSpace(r.Form.Get("action"))
	var args []string
	var label string
	switch action {
	case "net-dhcp-leases", "net-info":
		s.renderNetworkDiagnostic(w, r, host, networkName, action)
		return
	case "net-start":
		args = []string{"net-start", networkName}
		label = "启动虚拟网络 " + networkName
	case "net-destroy":
		if r.Form.Get("confirm") != "yes" {
			s.redirectError(w, r, "/hosts/"+host.ID+"/networks", "销毁虚拟网络需要显式确认")
			return
		}
		args = []string{"net-destroy", networkName}
		label = "停止虚拟网络 " + networkName
	case "net-autostart-on":
		args = []string{"net-autostart", networkName}
		label = "设置虚拟网络自启动 " + networkName
	case "net-autostart-off":
		args = []string{"net-autostart", "--disable", networkName}
		label = "取消虚拟网络自启动 " + networkName
	default:
		s.redirectError(w, r, "/hosts/"+host.ID+"/networks", "未知网络操作")
		return
	}
	sess, _ := sessionFrom(r.Context())
	jobID, err := s.enqueueCommand(r, sess.User, host.ID, "network-action", label, "virsh", args, "", boundedOperationTimeout(s.cfg.MaxTimeout, 120))
	if err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/networks", err.Error())
		return
	}
	// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
	http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
}

func (s *Server) vmDiskResize(w http.ResponseWriter, r *http.Request) {
	host, err := s.db.GetHost(r.Context(), r.PathValue("id"))
	if err != nil {
		s.hostLookupError(w, r, err)
		return
	}
	vmName := r.PathValue("vm")
	if err := libvirt.ValidateName(vmName); err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/vms", "虚拟机名称无效")
		return
	}
	target := strings.TrimSpace(r.Form.Get("disk_target"))
	amount := strings.ToUpper(strings.TrimSpace(r.Form.Get("disk_amount")))
	mode := strings.ToLower(strings.TrimSpace(r.Form.Get("disk_mode")))
	if _, err := parseScaledAmount(amount); err != nil {
		s.redirectError(w, r, vmRedirect(host.ID, vmName), "容量调整值无效，例如 10G")
		return
	}
	detail, err := s.libvirt.Detail(r.Context(), host.ID, vmName, false)
	if err != nil {
		s.redirectError(w, r, vmRedirect(host.ID, vmName), "无法读取虚拟机磁盘信息")
		return
	}
	disk, ok := findDiskDevice(detail.BlockList, target)
	if !ok {
		s.redirectError(w, r, vmRedirect(host.ID, vmName), "请选择有效的数据磁盘")
		return
	}
	state := strings.ToLower(strings.TrimSpace(detail.Domain.State))
	var tool string
	var args []string
	label := fmt.Sprintf("%s: %s 磁盘 %s %s", vmName, diskModeLabel(mode), disk.Target, amount)
	switch mode {
	case "grow":
		if state == "running" || state == "paused" {
			current, err := s.libvirt.BlockDeviceCapacity(r.Context(), host.ID, vmName, disk.Target)
			if err != nil {
				s.redirectError(w, r, vmRedirect(host.ID, vmName), "无法读取当前磁盘容量")
				return
			}
			delta, _ := parseScaledAmount(amount)
			if current > math.MaxUint64-delta {
				s.redirectError(w, r, vmRedirect(host.ID, vmName), "调整后磁盘容量超出支持范围")
				return
			}
			tool = "virsh"
			args = []string{"blockresize", vmName, disk.Target, strconv.FormatUint(current+delta, 10)}
		} else if state == "shut off" {
			tool = "qemu-img"
			args = []string{"resize", disk.Source, "+" + amount}
		} else {
			s.redirectError(w, r, vmRedirect(host.ID, vmName), "当前电源状态不支持磁盘扩容")
			return
		}
	case "shrink":
		if state != "shut off" {
			s.redirectError(w, r, vmRedirect(host.ID, vmName), "磁盘缩容前必须先关闭虚拟机")
			return
		}
		if r.Form.Get("confirm_text") != "SHRINK" {
			s.redirectError(w, r, vmRedirect(host.ID, vmName), "磁盘缩容必须输入 SHRINK")
			return
		}
		tool = "qemu-img"
		args = []string{"resize", "--shrink", disk.Source, "-" + amount}
	default:
		s.redirectError(w, r, vmRedirect(host.ID, vmName), "请选择扩容或缩容")
		return
	}
	sess, _ := sessionFrom(r.Context())
	jobID, err := s.enqueueCommand(r, sess.User, host.ID, "disk-action", label, tool, args, "", boundedOperationTimeout(s.cfg.MaxTimeout, 600))
	if err != nil {
		s.redirectError(w, r, vmRedirect(host.ID, vmName), err.Error())
		return
	}
	// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
	http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
}

func findDiskDevice(devices []libvirt.BlockDevice, target string) (libvirt.BlockDevice, bool) {
	for _, disk := range devices {
		if disk.Target == target && strings.EqualFold(disk.Device, "disk") &&
			(strings.EqualFold(disk.Type, "file") || strings.EqualFold(disk.Type, "block")) {
			return disk, true
		}
	}
	return libvirt.BlockDevice{}, false
}

func parseScaledAmount(raw string) (uint64, error) {
	if raw == "" || len(raw) > 20 {
		return 0, fmt.Errorf("empty or oversized amount")
	}
	multiplier := uint64(1)
	number := raw
	switch raw[len(raw)-1] {
	case 'K':
		multiplier = 1 << 10
		number = raw[:len(raw)-1]
	case 'M':
		multiplier = 1 << 20
		number = raw[:len(raw)-1]
	case 'G':
		multiplier = 1 << 30
		number = raw[:len(raw)-1]
	case 'T':
		multiplier = 1 << 40
		number = raw[:len(raw)-1]
	case 'P':
		multiplier = 1 << 50
		number = raw[:len(raw)-1]
	case 'E':
		multiplier = 1 << 60
		number = raw[:len(raw)-1]
	}
	if number == "" || strings.HasPrefix(number, "+") || strings.HasPrefix(number, "-") {
		return 0, fmt.Errorf("amount must be positive")
	}
	value, err := strconv.ParseUint(number, 10, 64)
	if err != nil || value == 0 {
		return 0, fmt.Errorf("invalid amount")
	}
	if value > math.MaxUint64/multiplier {
		return 0, fmt.Errorf("amount is too large")
	}
	return value * multiplier, nil
}

func validVolumeFormat(format string) bool {
	switch format {
	case "raw", "qcow", "qcow2", "qed", "vmdk", "iso":
		return true
	default:
		return false
	}
}

func diskModeLabel(mode string) string {
	if mode == "shrink" {
		return "缩容"
	}
	return "扩容"
}

func storageRedirect(hostID, pool string) string {
	path := "/hosts/" + hostID + "/storage"
	if pool != "" {
		path += "?pool=" + url.QueryEscape(pool)
	}
	return path
}

func vmRedirect(hostID, vmName string) string {
	return "/hosts/" + hostID + "/vms/" + url.PathEscape(vmName)
}

func boundedOperationTimeout(maximum time.Duration, desired int) int {
	maxSeconds := int(maximum.Seconds())
	if maxSeconds <= 0 || desired < 10 {
		return 10
	}
	if desired > maxSeconds {
		return maxSeconds
	}
	return desired
}

func (s *Server) renderNetworkDiagnostic(w http.ResponseWriter, r *http.Request, host store.Host, networkName, action string) {
	args := []string{action, networkName}
	result, err := s.libvirt.RunReadOnly(r.Context(), host.ID, args, 15*time.Second)
	output := strings.TrimSpace(result.Output())
	if output == "" && err != nil {
		output = "无法读取网络诊断信息，请检查主机连接和 libvirt 日志。"
	}
	title := "虚拟网络详情"
	if action == "net-dhcp-leases" {
		title = "DHCP 租约"
	}
	s.render(w, r, "diagnostic", pageData{Title: title, Nav: "hosts", Data: map[string]any{
		"Host": host, "Heading": title + " · " + networkName, "Back": "/hosts/" + host.ID + "/networks", "Output": output,
	}})
}

func (s *Server) renderStorageDiagnostic(w http.ResponseWriter, r *http.Request, host store.Host, pool string) {
	result, err := s.libvirt.RunReadOnly(r.Context(), host.ID, []string{"pool-info", pool}, 15*time.Second)
	output := strings.TrimSpace(result.Output())
	if output == "" && err != nil {
		output = "无法读取存储池信息，请检查主机连接和 libvirt 日志。"
	}
	s.render(w, r, "diagnostic", pageData{Title: "存储池详情", Nav: "hosts", Data: map[string]any{
		"Host": host, "Heading": "存储池详情 · " + pool, "Back": "/hosts/" + host.ID + "/storage?pool=" + url.QueryEscape(pool), "Output": output,
	}})
}
