func (s *Server) setupPage(w http.ResponseWriter, r *http.Request) {
	hosts, err := s.db.ListHosts(r.Context())
	if err != nil {
		s.serverError(w, r, err)
		return
	}
	s.render(w, r, "setup", pageData{Title: "首次运行", Nav: "dashboard", Data: map[string]any{
		"Checks": localVirtualizationChecks(), "Hosts": len(hosts),
	}})
}

func localVirtualizationChecks() []kvRow {
	return []kvRow{
		{Key: "KVM", Value: checkState(pathExists("/dev/kvm"))},
		{Key: "libvirt", Value: checkState(commandExists("virsh"))},
		{Key: "虚拟化工具", Value: checkState(commandExists("virt-host-validate"))},
	}
}

func checkState(ok bool) string {
	if ok {
		return "可用"
	}
	return "未检测到"
}

func pathExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func commandExists(name string) bool {
	_, err := os.Stat("/usr/bin/" + name)
	if err == nil {
		return true
	}
	_, err = os.Stat("/usr/sbin/" + name)
	return err == nil
}

func (s *Server) setupApply(w http.ResponseWriter, r *http.Request) {
	if r.Form.Get("confirm") != "yes" {
		s.redirectError(w, r, "/setup", "初始化默认资源需要确认")
		return
	}
	sess, _ := sessionFrom(r.Context())
	hosts, err := s.db.ListHosts(r.Context())
	if err != nil || len(hosts) == 0 {
		s.redirectError(w, r, "/hosts/new", "请先添加本机 libvirt 主机")
		return
	}
	host, ok := localSetupHost(hosts, s.cipher)
	if !ok {
		s.redirectError(w, r, "/hosts/new", "请先添加本机 libvirt 主机")
		return
	}
	pools, poolErr := s.libvirt.ListPools(r.Context(), host.ID)
	networks, networkErr := s.libvirt.ListNetworks(r.Context(), host.ID)
	if poolErr != nil || networkErr != nil {
		s.redirectError(w, r, "/setup", "无法读取现有默认资源")
		return
	}
	var jobID string
	var notices []string
	occupied, occupiedErr := defaultPoolPathOccupied(r.Context(), s.libvirt, host.ID, pools)
	if occupiedErr != nil {
		s.redirectError(w, r, "/setup", "无法读取现有默认资源")
		return
	}
	if !namedResourceExists(pools, "default") && occupied {
		notices = append(notices, "默认存储目录已被其他存储池使用，未创建 default")
	} else if !namedResourceExists(pools, "default") {
		poolXML, err := command.StoragePoolXML("dir", "default", "/var/lib/libvirt/images", "/var/lib/libvirt/images")
		if err != nil {
			s.serverError(w, r, err)
			return
		}
		poolSteps := []struct {
			label string
			args  []string
			stdin string
		}{
			{"初始化默认存储池", []string{"pool-define", "/dev/stdin"}, poolXML},
			{"启动默认存储池", []string{"pool-start", "default"}, ""},
			{"默认存储池开机自启", []string{"pool-autostart", "default"}, ""},
		}
		for i, step := range poolSteps {
			if i > 0 {
				time.Sleep(2 * time.Millisecond)
			}
			id, err := s.enqueueCommand(r, sess.User, host.ID, "storage-action", step.label, "virsh", step.args, step.stdin, 120)
			if err != nil {
				s.redirectError(w, r, "/setup", "无法初始化默认存储池")
				return
			}
			jobID = id
		}
	}
	if !namedNetworkExists(networks, "default") {
		netXML, err := command.NetworkXML(command.NetworkDefinition{Name: "default", Mode: "nat", Address: "192.168.122.0", Prefix: 24})
		if err != nil || command.ValidateNetworkXML(netXML) != nil {
			s.redirectError(w, r, "/setup", "默认网络定义无效")
			return
		}
		netSteps := []struct {
			label string
			args  []string
			stdin string
		}{
			{"初始化默认网络", []string{"net-define", "/dev/stdin"}, netXML},
			{"启动默认网络", []string{"net-start", "default"}, ""},
			{"默认网络开机自启", []string{"net-autostart", "default"}, ""},
		}
		for i, step := range netSteps {
			if i > 0 {
				time.Sleep(2 * time.Millisecond)
			}
			id, err := s.enqueueCommand(r, sess.User, host.ID, "network-action", step.label, "virsh", step.args, step.stdin, 120)
			if err != nil {
				s.redirectError(w, r, "/setup", "无法初始化默认网络")
				return
			}
			jobID = id
		}
	}
	if jobID == "" {
		message := "默认资源已存在，未重复创建"
		if len(notices) > 0 {
			message = strings.Join(notices, "；")
		}
		http.Redirect(w, r, flashURL("/setup", message, "ok"), http.StatusSeeOther)
		return
	}
	s.audit.Record(r.Context(), store.Audit{ActorID: sess.User.ID, ActorName: sess.User.Username, Action: "setup.defaults", HostID: host.ID, RemoteIP: s.clientIP(r)})
	// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
	http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
}

func defaultPoolPathOccupied(ctx context.Context, service interface {
	PoolTargetPath(context.Context, string, string) (string, error)
}, hostID string, items []libvirt.Pool) (bool, error) {
	const target = "/var/lib/libvirt/images"
	for _, item := range items {
		if item.Name == "" || item.Name == "default" {
			continue
		}
		path, err := service.PoolTargetPath(ctx, hostID, item.Name)
		if err != nil {
			return false, err
		}
		if filepath.Clean(path) == target {
			return true, nil
		}
	}
	return false, nil
}

func namedResourceExists(items []libvirt.Pool, name string) bool {
	for _, item := range items {
		if item.Name == name {
			return true
		}
	}
	return false
}

func namedNetworkExists(items []libvirt.Network, name string) bool {
	for _, item := range items {
		if item.Name == name {
			return true
		}
	}
	return false
}

func localSetupHost(hosts []store.Host, cipher *secret.Cipher) (store.Host, bool) {
	for _, host := range hosts {
		if !host.Enabled {
			continue
		}
		uri, err := libvirt.DecryptURI(cipher, host)
		if err == nil && (uri == "qemu:///system" || uri == "qemu+unix:///system") {
			return host, true
		}
	}
	return store.Host{}, false
}

func setupNeeded(hostCount int) bool {
	return hostCount == 0 || strings.TrimSpace(os.Getenv("WVC_SHOW_SETUP")) == "1"
}
