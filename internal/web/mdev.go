package web

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/http"
	"strings"

	"webvirtcloud-go/internal/command"
)

func (s *Server) mdevDefine(w http.ResponseWriter, r *http.Request) {
	hostID := r.PathValue("id")
	parent := strings.TrimSpace(r.Form.Get("parent"))
	kind := strings.TrimSpace(r.Form.Get("mdev_type"))
	if !validNodeName(parent) || !validNodeName(kind) {
		s.redirectError(w, r, "/hosts/"+hostID+"/vms", "介导设备参数无效")
		return
	}
	var raw [4]byte
	if _, err := rand.Read(raw[:]); err != nil {
		s.serverError(w, r, err)
		return
	}
	xmlText := fmt.Sprintf("<device><name>mdev_%s</name><parent>%s</parent><capability type='mdev'><type id='%s'/></capability></device>", hex.EncodeToString(raw[:]), parent, kind)
	if err := command.ValidateMDEVDefine(xmlText); err != nil {
		s.redirectError(w, r, "/hosts/"+hostID+"/vms", err.Error())
		return
	}
	sess, _ := sessionFrom(r.Context())
	jobID, err := s.enqueueCommand(r, sess.User, hostID, "host-mdev", "切分介导设备 "+parent, "virsh", []string{"nodedev-define", "/dev/stdin"}, xmlText, 60)
	if err != nil {
		s.redirectError(w, r, "/hosts/"+hostID+"/vms", err.Error())
		return
	}
	// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
	http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
}

func validNodeName(value string) bool {
	if value == "" || len(value) > 80 || strings.Contains(value, "..") {
		return false
	}
	for _, r := range value {
		if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') && r != '_' && r != '-' && r != '.' && r != ':' {
			return false
		}
	}
	return true
}
