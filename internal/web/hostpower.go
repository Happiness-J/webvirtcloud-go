package web

import (
	"errors"
	"net/http"
	"strings"

	"webvirtcloud-go/internal/command"
	"webvirtcloud-go/internal/store"
)

func (s *Server) hostPowerPage(w http.ResponseWriter, r *http.Request) {
	host, err := s.db.GetHost(r.Context(), r.PathValue("id"))
	if err != nil {
		s.hostLookupError(w, r, err)
		return
	}
	s.render(w, r, "host_power", pageData{Title: "宿主机健康", Nav: "hosts", Data: map[string]any{"Host": host}})
}

func (s *Server) hostPowerAction(w http.ResponseWriter, r *http.Request) {
	host, err := s.db.GetHost(r.Context(), r.PathValue("id"))
	if err != nil {
		s.hostLookupError(w, r, err)
		return
	}
	action := strings.TrimSpace(r.Form.Get("action"))
	tool, args, label, err := hostPowerCommand(action, strings.TrimSpace(r.Form.Get("value")))
	if err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/power", err.Error())
		return
	}
	if _, err := command.JobMinimumRole("host-power", tool, args); err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/power", "宿主机操作参数无效")
		return
	}
	if (action == "reboot" || action == "poweroff") && r.Form.Get("confirm") != "yes" {
		s.redirectError(w, r, "/hosts/"+host.ID+"/power", "重启或关机需要确认")
		return
	}
	sess, _ := sessionFrom(r.Context())
	jobID, err := s.enqueueCommand(r, sess.User, host.ID, "host-power", label, tool, args, "", 120)
	if err != nil {
		s.redirectError(w, r, "/hosts/"+host.ID+"/power", err.Error())
		return
	}
	s.audit.Record(r.Context(), store.Audit{ActorID: sess.User.ID, ActorName: sess.User.Username, Action: "host.power." + action, HostID: host.ID, RemoteIP: s.clientIP(r)})
	// #nosec G710 -- jobID is generated by the enqueue path and the destination is a local fixed prefix.
	http.Redirect(w, r, "/jobs/"+jobID, http.StatusSeeOther)
}

func hostPowerCommand(action, value string) (string, []string, string, error) {
	switch action {
	case "smart":
		if value == "" {
			value = "/dev/sda"
		}
		return "smartctl", []string{"-H", value}, "检查磁盘健康 " + value, nil
	case "sensors":
		return "sensors", []string{"-u"}, "读取温度和风扇", nil
	case "updates":
		return "apt-get", []string{"-s", "upgrade"}, "检查可用更新", nil
	case "reboot":
		return "systemctl", []string{"reboot"}, "重启宿主机", nil
	case "poweroff":
		return "systemctl", []string{"poweroff"}, "关闭宿主机", nil
	case "wol":
		return "etherwake", []string{value}, "网络唤醒 " + value, nil
	default:
		return "", nil, "", errors.New("未知宿主机操作")
	}
}
